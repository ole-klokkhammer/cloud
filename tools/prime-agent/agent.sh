#!/usr/bin/env bash
#
# agent.sh — register a Prime Agent workbench service per workspace
#            (podman compose edition).
#
# Model B (one service per workspace, keep-alive + manual start):
#
#   agent.sh <workspace-path>              register + start  prime-agent-<slug>
#   agent.sh <workspace-path> <slug>       register with an explicit service suffix
#   agent.sh remove  <slug>                stop + unregister + drop its state volume
#   agent.sh list                          show every registered workspace
#   agent.sh exec|shell|status|logs|ps|start|stop  <slug>
#
# Behaviour:
#   * For each workspace a compose project is written to
#         ~/.config/prime-agent/<slug>/compose.yaml
#     and managed with  podman compose -f <file>  (docker-compose provider
#     talking to the rootless podman API socket, which this script enables).
#   * The main process is a keep-alive (`command: sleep infinity`). Start the
#     interactive TUI on demand:  agent.sh exec <slug>
#   * Each workspace gets its own named state volume (prime-agent-<slug>-state),
#     so N workspaces can run side by side without clobbering each other's
#     sessions / kernel venv. Container and volume names match the old quadlet
#     layout, so registering a workspace that is still a quadlet unit migrates
#     it to compose in place (state volume survives).
#   * Unlike quadlets, compose projects are NOT wired into systemd: after a
#     host reboot, re-run  agent.sh <path>  (idempotent) to bring them back.
#
# Prereqs: build the image (cd podman && ./build.sh). The rootless podman
# socket is enabled automatically on first use.

set -euo pipefail

IMAGE="prime-agent:latest"
BASE_DIR="${HOME}/.config/prime-agent"
LEGACY_SYSDDIR="${HOME}/.config/containers/systemd"
APPLIANCE_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
MODEL_JSON="${APPLIANCE_DIR}/podman/models.json"

die() { echo "agent.sh: error: $*" >&2; exit 1; }
slunit() { echo "prime-agent-$1"; }
projfile() { echo "${BASE_DIR}/$1/compose.yaml"; }

# slug: lowercase, non-alnum -> '-', squeeze runs, trim edge dashes.
sanitize() {
    echo "$1" | tr '[:upper:]' '[:lower:]' | sed -E 's/[^a-z0-9]+/-/g; s/^-+//; s/-+$//'
}

require_image() {
    if ! podman image exists "${IMAGE}" >/dev/null 2>&1; then
        echo "agent.sh: image ${IMAGE} not present."
        echo "        build it first:  cd ${APPLIANCE_DIR}/podman && ./build.sh"
        exit 1
    fi
}

require_socket() {
    systemctl --user is-active --quiet podman.socket 2>/dev/null && return 0
    echo "agent.sh: enabling the rootless podman API socket (compose needs it)"
    systemctl --user enable --now podman.socket
}

compose() {
    local slug="${1:?slug}"; shift
    local f; f="$(projfile "$slug")"
    [[ -f "$f" ]] || die "no compose project for '${slug}' (${f}); register it: agent.sh <workspace-path> [slug]"
    podman compose -f "$f" "$@"
}

# Tear down an old quadlet registration (unit + file + stale container) if
# present. Leaves the state volume alone - compose reuses it.
retire_legacy_quadlet() {
    local slug="$1" unit q
    unit="$(slunit "$slug")"
    q="${LEGACY_SYSDDIR}/${unit}.container"
    [[ -f "$q" ]] || return 0
    echo "agent.sh: migrating ${unit}: quadlet -> compose"
    systemctl --user stop "${unit}" 2>/dev/null || true
    systemctl --user disable "${unit}" 2>/dev/null || true
    rm -f "$q"
    systemctl --user daemon-reload 2>/dev/null || true
    podman rm -f "${unit}" 2>/dev/null || true
}

register() {
    local ws="${1:?usage: agent.sh <workspace-path> [slug]}"
    local slug="${2:-$(sanitize "$(basename "$(realpath "$ws")")")}"
    local unit dir f

    ws="$(realpath "$ws")"
    [[ -d "$ws" ]] || die "workspace is not a directory: ${ws}"
    [[ -n "$slug" ]] || die "could not derive a service slug from ${ws}"
    [[ -f "$MODEL_JSON" ]] || die "models.json not found at ${MODEL_JSON}"
    require_image
    require_socket

    unit="$(slunit "$slug")"
    dir="${BASE_DIR}/${slug}"
    f="${dir}/compose.yaml"
    mkdir -p "$dir"
    retire_legacy_quadlet "$slug"

    cat > "$f" <<EOF
# ${unit} - Prime Agent workbench for ${ws}
# Generated by agent.sh. Do not edit by hand; re-register or \`agent.sh remove ${slug}\`.
name: ${unit}
services:
  agent:
    image: ${IMAGE}
    container_name: ${unit}
    hostname: ${unit}
    network_mode: host
    working_dir: /workspace
    # Keep-alive; drive the TUI with: agent.sh exec ${slug}
    command: sleep infinity
    stdin_open: true
    tty: true
    restart: unless-stopped
    environment:
      PRIME_AGENT_CODING_AGENT_DIR: /home/agent/.prime/agent
      LOCAL_LLM_KEY: dummy
      TZ: Europe/Oslo
    volumes:
      # Attach this workspace read-write.
      - ${ws}:/workspace:rw
      # Per-workspace persistent state (sessions, auth.json, kernel venv).
      - state:/home/agent/.prime/agent
      # LLM provider config - the repo copy is the source of truth (read-only).
      - ${MODEL_JSON}:/home/agent/.prime/agent/models.json:ro
volumes:
  state:
    name: ${unit}-state
EOF

    compose "$slug" up -d --pull never

    echo "registered ${unit} -> ${ws}"
    echo "  state volume : ${unit}-state"
    echo "  start TUI    : agent.sh exec ${slug}"
    echo "  compose file : ${f}"
}

remove() {
    local slug="${1:?usage: agent.sh remove <slug>}"
    local unit f
    unit="$(slunit "$slug")"
    f="$(projfile "$slug")"

    retire_legacy_quadlet "$slug"
    if [[ -f "$f" ]]; then
        compose "$slug" down -v 2>/dev/null || {
            # rootless-netns teardown quirk: hard-remove as fallback.
            podman rm -f "${unit}" 2>/dev/null || true
            podman volume rm "${unit}-state" 2>/dev/null || true
        }
        rm -rf "${BASE_DIR}/${slug}"
    else
        podman volume rm "${unit}-state" 2>/dev/null || true
    fi
    echo "removed ${unit}"
}

list() {
    local f slug ws state found=0
    for f in "${BASE_DIR}"/*/compose.yaml; do
        [[ -e "$f" ]] || continue
        slug="$(basename "$(dirname "$f")")"
        ws="$(grep -Em1 ':/workspace' "$f" | sed -E 's|^[[:space:]]*- (.*):/workspace.*|\1|')"
        state="$(podman inspect -f '{{.State.Status}}' "$(slunit "$slug")" 2>/dev/null || echo stopped)"
        found=1
        printf '%-32s %-10s %s\n' "$(slunit "$slug")" "$state" "$ws"
    done
    [[ "$found" -eq 1 ]] || echo "(no workspaces registered)"
    for f in "${LEGACY_SYSDDIR}"/prime-agent-*.container; do
        [[ -e "$f" ]] || continue
        echo "note: legacy quadlet $(basename "$f") installed -> re-register its slug to migrate to compose"
    done
}

# ---- dispatch -------------------------------------------------------------
cmd="${1:-list}"
case "$cmd" in
    remove|list|exec|shell|status|logs|ps|start|stop) shift ;;
    -*|help|-h)
        grep -E '^#( |$)' "$0" | sed -n '1,52p'; exit 0 ;;
esac

case "$cmd" in
    list) list ;;
    remove) remove "${1:?slug}" ;;
    exec|shell)
        local_slug="${1:?slug}"; unit="$(slunit "$local_slug")"
        case "$cmd" in
            exec)  podman exec -it "$unit" prime-agent ;;
            shell) podman exec -it "$unit" sh ;;
        esac ;;
    status) compose "${1:?slug}" ps ;;
    start)  require_socket; compose "${1:?slug}" up -d --pull never ;;
    stop)   compose "${1:?slug}" stop ;;
    logs)
        unit="$(slunit "${1:?slug}")"
        podman logs --tail 40 "$unit" 2>&1
        echo "--- following (Ctrl-C to stop) ---"
        podman logs -f "$unit" ;;
    ps) podman ps -a --filter "name=prime-agent-${1:?slug}" ;;
    *) # first arg is a workspace path -> register. No shift here, so keep
       # the original positionals: $1 = workspace, $2 = optional slug.
       register "$1" "${2:-}" ;;
esac
